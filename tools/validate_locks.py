"""Validate installer lock files before native clean-machine testing.

Pip's hash mode requires extras to be pinned explicitly.  A resolver may emit
``package==version`` even when an input requested ``package[extra]==version``;
that looks complete but fails later when a dependency asks for that extra.
"""

from __future__ import annotations

import re
from pathlib import Path


ROOT = Path(__file__).resolve().parent.parent
LOCKS = (
    (ROOT / "platforms/windows/source/requirements-windows.in",
     ROOT / "platforms/windows/source/requirements-windows.lock"),
    (ROOT / "platforms/macos/source/requirements-macos.in",
     ROOT / "platforms/macos/source/requirements-macos.lock"),
)
PIN = re.compile(r"^([A-Za-z0-9_.-]+(?:\[[A-Za-z0-9_,.-]+\])?)==([^\s\\;]+)")


def normalized(value: str) -> str:
    return value.lower().replace("_", "-")


def validate(source: Path, lock: Path) -> None:
    lock_text = lock.read_text(encoding="utf-8")
    if not lock_text.startswith("# This file was autogenerated"):
        raise SystemExit(f"Missing generated-lock header: {lock.relative_to(ROOT)}")

    entries: dict[str, tuple[str, str]] = {}
    lines = lock_text.splitlines()
    for index, line in enumerate(lines):
        if not line or line[0].isspace() or line.startswith("#"):
            continue
        match = PIN.match(line)
        if not match:
            raise SystemExit(f"Unpinned lock entry in {lock.relative_to(ROOT)}:{index + 1}: {line}")
        key = normalized(match.group(1).split("[", 1)[0])
        block = "\n".join(lines[index:index + 12])
        if "--hash=sha256:" not in block:
            raise SystemExit(f"Missing hash for {match.group(1)} in {lock.relative_to(ROOT)}")
        entries[key] = (normalized(match.group(1)), match.group(2))

    for line in source.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "[" not in line:
            continue
        match = PIN.match(line)
        if not match:
            raise SystemExit(f"Extra requirement must be exactly pinned in {source.relative_to(ROOT)}: {line}")
        requested = normalized(match.group(1))
        key = requested.split("[", 1)[0]
        locked = entries.get(key)
        if locked != (requested, match.group(2)):
            raise SystemExit(
                f"Extra was lost from {lock.relative_to(ROOT)}: expected "
                f"{match.group(1)}=={match.group(2)}"
            )


if __name__ == "__main__":
    for pair in LOCKS:
        validate(*pair)
    print("Installer dependency locks: OK")
